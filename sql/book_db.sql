-- 删除已存在的数据库（如需保留历史数据请注释此行）
DROP DATABASE IF EXISTS book_db;

-- 创建数据库
CREATE DATABASE book_db DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;

-- 使用数据库
USE book_db;

-- ============================================================
-- 一、建表语句
-- ============================================================

-- 1. 系统用户表
CREATE TABLE sys_user (
    id          INT          NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    username    VARCHAR(50)  NOT NULL COMMENT '账号',
    password    VARCHAR(100) NOT NULL COMMENT '密码',
    nickname    VARCHAR(50)  DEFAULT NULL COMMENT '昵称',
    phone       VARCHAR(20)  DEFAULT NULL COMMENT '手机号',
    head_img    VARCHAR(255) DEFAULT NULL COMMENT '头像URL',
    role        VARCHAR(20)  DEFAULT 'student' COMMENT '角色：admin-管理员，student-学生',
    create_time DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    deleted     INT          DEFAULT 0 COMMENT '逻辑删除：0-未删除，1-已删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_username (username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='系统用户表';

-- 2. 图书信息表
CREATE TABLE book_info (
    id            INT          NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    book_name     VARCHAR(100) NOT NULL COMMENT '书名',
    author        VARCHAR(50)  DEFAULT NULL COMMENT '作者',
    category      VARCHAR(50)  DEFAULT NULL COMMENT '分类',
    publish_house VARCHAR(100) DEFAULT NULL COMMENT '出版社',
    stock         INT          DEFAULT 0 COMMENT '库存数量',
    book_desc     VARCHAR(500) DEFAULT NULL COMMENT '简介',
    create_time   DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time   DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    deleted       INT          DEFAULT 0 COMMENT '逻辑删除：0-未删除，1-已删除',
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='图书信息表';

-- 3. 借阅记录表
CREATE TABLE book_borrow (
    id          INT      NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    user_id     INT      NOT NULL COMMENT '借阅用户ID',
    book_id     INT      NOT NULL COMMENT '图书ID',
    borrow_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '借阅时间',
    return_time DATETIME DEFAULT NULL COMMENT '归还时间',
    status      VARCHAR(20) DEFAULT '借阅中' COMMENT '借阅状态：借阅中-未归还，已归还',
    PRIMARY KEY (id),
    KEY idx_user_id (user_id),
    KEY idx_book_id (book_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='借阅记录表';

